//! Dual-engine database access for the Tauri commands: SQLite (default,
//! embedded, offline-first) or PostgreSQL (opt-in).
//!
//! Like `zolai-tts/src/zolai_tts/db/drivers.py` and `db/drivers.py`, engine
//! selection is **configuration, not code**:
//!
//! - `ZOLAI_TAURI_DB_URL` (then legacy `ZOLAI_DB_URL`) selects the engine by
//!   scheme: `sqlite:///path` → embedded SQLite, `postgresql://…` /
//!   `postgres://…` → PostgreSQL.
//! - Unset → SQLite at `SQLITE_PATH` or `data/zolai.db` (unchanged default;
//!   normal builds are offline-first and need no server).
//! - The PostgreSQL client is only compiled with `--features postgres`
//!   (`tokio-postgres`); without it a postgres URL fails with a clear error.
//!
//! Portability rules shared by both engines (SQL written with `?N`
//! placeholders, translated to `$N` for PostgreSQL):
//!   * booleans as INTEGER 0/1; timestamps as ISO-8601 TEXT; JSON as TEXT;
//!   * upserts via `INSERT … ON CONFLICT (…) DO UPDATE SET …`;
//!   * no strftime()/datetime() SQL; only substr()/COALESCE/aggregates;
//!   * engine-specific DDL (PRAGMA, AUTOINCREMENT, sqlite_master) is isolated
//!     here, never in the commands.

use serde::{Deserialize, Serialize};
use std::path::PathBuf;

pub const VALID_TABLES: [&str; 8] = [
    "dictionary", "bible_verses", "grammar_patterns", "phrases", "vocab",
    "translations", "word_usage", "provenance",
];

const SCHEMA_SQL: &str = include_str!("../../db/schema.sql");

/// SQLite path fallback — identical to the historical `default_sqlite_path()`.
pub fn default_sqlite_path() -> PathBuf {
    std::env::var("SQLITE_PATH")
        .map(PathBuf::from)
        .unwrap_or_else(|_| PathBuf::from("data/zolai.db"))
}

/// Resolve `ZOLAI_TAURI_DB_URL` / `ZOLAI_DB_URL`; `Ok(None)` means "use the
/// legacy sqlite path default".
fn configured_url() -> Option<String> {
    for key in ["ZOLAI_TAURI_DB_URL", "ZOLAI_DB_URL"] {
        if let Ok(v) = std::env::var(key) {
            let v = v.trim().to_string();
            if !v.is_empty() {
                return Some(v);
            }
        }
    }
    None
}

/// `"postgres"` or `"sqlite"` for a configured URL (scheme decides).
pub fn dialect_of(url: &str) -> &'static str {
    let l = url.to_ascii_lowercase();
    if l.starts_with("postgres://") || l.starts_with("postgresql://") {
        "postgres"
    } else {
        "sqlite"
    }
}

/// Strip the `sqlite:///` scheme to a filesystem path.
fn sqlite_path_from(url: &str) -> PathBuf {
    let p = url
        .strip_prefix("sqlite:///")
        .or_else(|| url.strip_prefix("sqlite://"))
        .unwrap_or(url);
    PathBuf::from(p)
}

/// Rewrite `?N` placeholders to PostgreSQL `$N`.
pub fn translate_placeholders(sql: &str) -> String {
    let mut out = String::with_capacity(sql.len());
    let bytes = sql.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'?' && i + 1 < bytes.len() && bytes[i + 1].is_ascii_digit() {
            out.push('$');
            i += 1;
            while i < bytes.len() && bytes[i].is_ascii_digit() {
                out.push(bytes[i] as char);
                i += 1;
            }
        } else {
            out.push(bytes[i] as char);
            i += 1;
        }
    }
    out
}

/// Rewrite the shared-subset DDL in `db/schema.sql` to PostgreSQL.
/// Same rules as `db/drivers.py`: drop PRAGMAs, AUTOINCREMENT → identity.
pub fn translate_ddl(sql: &str) -> Vec<String> {
    sql.split(';')
        .map(|s| s.trim().to_string())
        .filter(|s| !s.is_empty())
        // Strip leading SQL comments so a chunk like
        // `-- header\nPRAGMA journal_mode=WAL` is still recognised as a PRAGMA
        // (schema files start with comments, which used to defeat the filter
        // below and send a syntax error to the server).
        .map(|s| {
            s.lines()
                .skip_while(|line| {
                    let t = line.trim();
                    t.is_empty() || t.starts_with("--")
                })
                .collect::<Vec<_>>()
                .join("\n")
                .trim()
                .to_string()
        })
        .filter(|s| !s.is_empty() && !s.to_ascii_uppercase().starts_with("PRAGMA"))
        .map(|s| {
            s.replace("AUTOINCREMENT", "GENERATED BY DEFAULT AS IDENTITY")
        })
        .collect()
}

#[derive(Serialize)]
pub struct DbInitResult {
    pub ok: bool,
    pub engine: String,
    pub db_path: String,
    pub tables_created: usize,
    pub error: Option<String>,
}

#[derive(Serialize, Deserialize, Debug, PartialEq, Eq)]
pub struct DictEntry {
    pub zolai: String,
    pub english: String,
    pub english_clean: Option<String>,
    pub source: String,
    pub pos: String,
}

#[derive(Serialize, Deserialize, Debug, PartialEq, Eq)]
pub struct BibleVerse {
    pub ref_id: String,
    pub book: String,
    pub chapter: i32,
    pub verse: i32,
    pub zo_tdb77: String,
    pub zo_tedim2010: String,
    pub en_kjv: String,
}

#[derive(Serialize, Deserialize, Debug, PartialEq, Eq)]
pub struct CountResult {
    pub table: String,
    pub count: i64,
}

/// The handful of operations the Tauri commands actually use, per engine.
pub enum Db {
    Sqlite(rusqlite::Connection),
    #[cfg(feature = "postgres")]
    Postgres(PostgresConn),
}

impl Db {
    /// Open according to configuration. Default (no env) = SQLite, unchanged.
    pub fn open() -> Result<Db, String> {
        match configured_url() {
            None => Self::open_sqlite(&default_sqlite_path()),
            Some(url) if dialect_of(&url) == "postgres" => {
                #[cfg(feature = "postgres")]
                {
                    PostgresConn::connect(&url).map(Db::Postgres)
                }
                #[cfg(not(feature = "postgres"))]
                {
                    Err(format!(
                        "PostgreSQL URL configured ({url}) but this binary was built \
                         without postgres support. Rebuild with `--features postgres`."
                    ))
                }
            }
            Some(url) => Self::open_sqlite(&sqlite_path_from(&url)),
        }
    }

    fn open_sqlite(path: &std::path::Path) -> Result<Db, String> {
        if let Some(parent) = path.parent() {
            if !parent.as_os_str().is_empty() {
                std::fs::create_dir_all(parent)
                    .map_err(|e| format!("Failed to create db directory: {e}"))?;
            }
        }
        rusqlite::Connection::open(path)
            .map(Db::Sqlite)
            .map_err(|e| format!("Failed to open database: {e}"))
    }

    /// Non-secret description of the active connection ("sqlite:<path>" etc.).
    pub fn target(&self) -> String {
        match self {
            Db::Sqlite(conn) => {
                let p = conn.path().map(|s| s.to_string()).unwrap_or_else(|| "data/zolai.db".into());
                format!("sqlite:{p}")
            }
            #[cfg(feature = "postgres")]
            Db::Postgres(pg) => format!("postgres:{}", pg.host),
        }
    }

    pub fn engine(&self) -> &'static str {
        match self {
            Db::Sqlite(_) => "sqlite",
            #[cfg(feature = "postgres")]
            Db::Postgres(_) => "postgres",
        }
    }

    /// Create schema (idempotent) and return the number of app tables present.
    pub fn init(&self) -> Result<DbInitResult, String> {
        let engine = self.engine();
        let target = self.target();
        let result = match self {
            Db::Sqlite(conn) => {
                conn.execute_batch("PRAGMA journal_mode=WAL; PRAGMA foreign_keys=ON;")
                    .map_err(|e| format!("Failed to set pragmas: {e}"))?;
                conn.execute_batch(SCHEMA_SQL)
                    .map_err(|e| format!("Failed to create schema: {e}"))?;
                conn.query_row(
                    "SELECT COUNT(*) FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'",
                    [],
                    |row| row.get::<_, usize>(0),
                )
                .map_err(|e| format!("Failed to query table count: {e}"))
            }
            #[cfg(feature = "postgres")]
            Db::Postgres(pg) => pg.init_schema().map_err(|e| e.to_string()),
        }?;
        Ok(DbInitResult {
            ok: true,
            engine: engine.to_string(),
            db_path: target,
            tables_created: result,
            error: None,
        })
    }

    pub fn lookup_word(&self, word: &str) -> Result<Vec<DictEntry>, String> {
        let pattern = format!("%{word}%");
        match self {
            Db::Sqlite(conn) => {
                let mut stmt = conn
                    .prepare(
                        "SELECT zolai, english, english_clean, source, pos
                         FROM dictionary
                         WHERE zolai LIKE ?1 OR english LIKE ?1
                         LIMIT 50",
                    )
                    .map_err(|e| format!("Failed to prepare query: {e}"))?;
                let entries = stmt
                    .query_map(rusqlite::params![pattern], |row| {
                        Ok(DictEntry {
                            zolai: row.get(0)?,
                            english: row.get(1)?,
                            english_clean: row.get(2)?,
                            source: row.get(3)?,
                            pos: row.get(4)?,
                        })
                    })
                    .map_err(|e| format!("Query failed: {e}"))?
                    .collect::<Result<Vec<_>, _>>()
                    .map_err(|e| format!("Failed to collect results: {e}"))?;
                Ok(entries)
            }
            #[cfg(feature = "postgres")]
            Db::Postgres(pg) => pg.lookup_word(word),
        }
    }

    pub fn search_bible(&self, query: &str) -> Result<Vec<BibleVerse>, String> {
        let pattern = format!("%{query}%");
        match self {
            Db::Sqlite(conn) => {
                let mut stmt = conn
                    .prepare(
                        "SELECT ref, book, chapter, verse, zo_tdb77, zo_tedim2010, en_kJV
                         FROM bible_verses
                         WHERE zo_tdb77 LIKE ?1 OR zo_tedim2010 LIKE ?1 OR en_kJV LIKE ?1
                         LIMIT 100",
                    )
                    .map_err(|e| format!("Failed to prepare query: {e}"))?;
                let verses = stmt
                    .query_map(rusqlite::params![pattern], |row| {
                        Ok(BibleVerse {
                            ref_id: row.get(0)?,
                            book: row.get(1)?,
                            chapter: row.get(2)?,
                            verse: row.get(3)?,
                            zo_tdb77: row.get(4)?,
                            zo_tedim2010: row.get(5)?,
                            en_kjv: row.get(6)?,
                        })
                    })
                    .map_err(|e| format!("Query failed: {e}"))?
                    .collect::<Result<Vec<_>, _>>()
                    .map_err(|e| format!("Failed to collect results: {e}"))?;
                Ok(verses)
            }
            #[cfg(feature = "postgres")]
            Db::Postgres(pg) => pg.search_bible(query),
        }
    }

    pub fn count_table(&self, table: &str) -> Result<CountResult, String> {
        if !VALID_TABLES.contains(&table) {
            return Err(format!("Invalid table name: {table}"));
        }
        let sql = format!("SELECT COUNT(*) FROM {table}");
        let count = match self {
            Db::Sqlite(conn) => conn
                .query_row(&sql, [], |row| row.get::<_, i64>(0))
                .map_err(|e| format!("Query failed: {e}"))?,
            #[cfg(feature = "postgres")]
            Db::Postgres(pg) => pg.count_table(table)?,
        };
        Ok(CountResult {
            table: table.to_string(),
            count,
        })
    }
}

// ── PostgreSQL implementation (only with `--features postgres`) ────────────

#[cfg(feature = "postgres")]
pub struct PostgresConn {
    /// Dedicated single-threaded runtime (sync Tauri commands drive the
    /// async tokio-postgres client through it).
    rt: tokio::runtime::Runtime,
    client: tokio_postgres::Client,
    host: String,
}

#[cfg(feature = "postgres")]
impl PostgresConn {
    fn connect(url: &str) -> Result<Self, String> {
        let rt = tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .map_err(|e| format!("failed to build pg runtime: {e}"))?;
        let (client, connection) = rt
            .block_on(tokio_postgres::connect(url, tokio_postgres::NoTls))
            .map_err(|e| format!("Failed to open database: {e}"))?;
        let handle = rt.handle().clone();
        handle.spawn(async move {
            let _ = connection.await;
        });
        let host = url
            .split('@')
            .last()
            .and_then(|rest| rest.split('/').next())
            .unwrap_or("postgres")
            .to_string();
        Ok(PostgresConn { rt, client, host })
    }

    fn init_schema(&self) -> Result<usize, String> {
        for statement in translate_ddl(SCHEMA_SQL) {
            self.rt
                .block_on(self.client.execute(&statement, &[]))
                .map_err(|e| format!("Failed to create schema: {e}"))?;
        }
        let rows = self
            .rt
            .block_on(
                self.client.query(
                    "SELECT table_name FROM information_schema.tables WHERE table_schema = 'public'",
                    &[],
                ),
            )
            .map_err(|e| format!("Failed to query table count: {e}"))?;
        Ok(rows
            .iter()
            .filter_map(|r| r.get::<_, Option<String>>(0))
            .filter(|name| VALID_TABLES.contains(&name.as_str()))
            .count())
    }

    fn lookup_word(&self, word: &str) -> Result<Vec<DictEntry>, String> {
        let sql = translate_placeholders(
            "SELECT zolai, english, english_clean, source, pos
             FROM dictionary
             WHERE zolai LIKE ?1 OR english LIKE ?1
             LIMIT 50",
        );
        let pattern = format!("%{word}%");
        let rows = self
            .rt
            .block_on(self.client.query(&sql, &[&pattern]))
            .map_err(|e| format!("Query failed: {e}"))?;
        Ok(rows
            .iter()
            .map(|r| DictEntry {
                zolai: r.get(0),
                english: r.get(1),
                english_clean: r.get(2),
                source: r.get(3),
                pos: r.get(4),
            })
            .collect())
    }

    fn search_bible(&self, query: &str) -> Result<Vec<BibleVerse>, String> {
        let sql = translate_placeholders(
            "SELECT ref, book, chapter, verse, zo_tdb77, zo_tedim2010, en_kJV
             FROM bible_verses
             WHERE zo_tdb77 LIKE ?1 OR zo_tedim2010 LIKE ?1 OR en_kJV LIKE ?1
             LIMIT 100",
        );
        let pattern = format!("%{query}%");
        let rows = self
            .rt
            .block_on(self.client.query(&sql, &[&pattern]))
            .map_err(|e| format!("Query failed: {e}"))?;
        Ok(rows
            .iter()
            .map(|r| BibleVerse {
                ref_id: r.get(0),
                book: r.get(1),
                chapter: r.get(2),
                verse: r.get(3),
                zo_tdb77: r.get(4),
                zo_tedim2010: r.get(5),
                en_kjv: r.get(6),
            })
            .collect())
    }

    fn count_table(&self, table: &str) -> Result<i64, String> {
        let sql = format!("SELECT COUNT(*) FROM {table}");
        self.rt
            .block_on(self.client.query_one(&sql, &[]))
            .map(|r| r.get(0))
            .map_err(|e| format!("Query failed: {e}"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dialect_selection() {
        assert_eq!(dialect_of("postgresql://u@h/db"), "postgres");
        assert_eq!(dialect_of("postgres://u@h/db"), "postgres");
        assert_eq!(dialect_of("PostgreSQL://u@h/db"), "postgres");
        assert_eq!(dialect_of("sqlite:///data/db/zolai.sqlite3"), "sqlite");
        assert_eq!(dialect_of("plain/path.db"), "sqlite");
    }

    #[test]
    fn placeholder_translation() {
        assert_eq!(
            translate_placeholders("WHERE a LIKE ?1 OR b LIKE ?1 LIMIT 50"),
            "WHERE a LIKE $1 OR b LIKE $1 LIMIT 50"
        );
        assert_eq!(
            translate_placeholders("VALUES (?, ?)"),
            "VALUES (?, ?)" // unnamed ? is the Python layer's convention only
        );
        assert_eq!(translate_placeholders("100 ? 50"), "100 ? 50");
    }

    #[test]
    fn ddl_translation() {
        let stmts = translate_ddl("PRAGMA journal_mode=WAL;\nCREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT);");
        assert_eq!(stmts.len(), 1);
        assert!(stmts[0].contains("GENERATED BY DEFAULT AS IDENTITY"));
        assert!(!stmts[0].contains("AUTOINCREMENT"));
        assert!(!stmts.iter().any(|s| s.to_uppercase().contains("PRAGMA")));

        // Schema files start with comment headers; a PRAGMA hidden behind them
        // must still be filtered (it used to reach the server as raw SQL).
        let with_header = translate_ddl(
            "-- header\n-- more\nPRAGMA foreign_keys=ON;\n-- table\nCREATE TABLE u (id INTEGER PRIMARY KEY AUTOINCREMENT);",
        );
        assert_eq!(with_header.len(), 1);
        assert!(with_header[0].starts_with("CREATE TABLE u"));
    }

    #[test]
    fn sqlite_url_paths() {
        assert_eq!(sqlite_path_from("sqlite:///a/b.db"), PathBuf::from("a/b.db"));
        assert_eq!(sqlite_path_from("/a/b.db"), PathBuf::from("/a/b.db"));
    }

    #[test]
    fn table_allowlist_rejects_injection() {
        // count_table validates against VALID_TABLES before formatting SQL.
        assert!(!VALID_TABLES.contains(&"sqlite_master"));
        assert!(!VALID_TABLES.contains(&"dictionary; DROP TABLE x"));
    }

    #[test]
    fn sqlite_init_lookup_count_roundtrip() {
        // Default engine (embedded sqlite): init creates all 8 tables and the
        // query paths run against a real file exactly as before.
        let dir = std::env::temp_dir().join(format!("zolai-db-test-{}", std::process::id()));
        let path = dir.join("test.db");
        let db = Db::open_sqlite(&std::path::Path::new(&path)).expect("open");
        let res = db.init().expect("init");
        assert!(res.ok);
        assert_eq!(res.engine, "sqlite");
        assert_eq!(res.tables_created, 8);
        assert_eq!(db.count_table("dictionary").unwrap().count, 0);
        assert_eq!(db.lookup_word("siam").unwrap().len(), 0);
        assert_eq!(db.search_bible("in hiam").unwrap().len(), 0);
        assert!(db.count_table("evil_table").is_err());
        assert!(db.target().starts_with("sqlite:"));
        let _ = std::fs::remove_dir_all(&dir);
    }
}

